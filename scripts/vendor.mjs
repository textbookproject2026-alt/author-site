// What the author site's pages import from other people, kept in this site (site/vendor/),
// so the site loads scripts from itself alone (and Plausible): no CDN.
//
//   smartypants.js   retext 9.0.0 + retext-smartypants 6.2.0, the book site's typography
//                    (quartz-community github-flavored-markdown 3eabbaa locks them and
//                    unified 11.0.5 and the rest; package.json overrides pin the same)
//   markdownlint.js  markdownlint 0.38.0's lib/markdownlint.mjs: the formatting check
//   js-yaml.js       js-yaml 4.1.0: the formatting check's config, Credits' frontmatter
//   pyodide/         Pyodide 314.0.7's core files, as npm has them: the questions
//
// Each bundle (esbuild, one ES module) lists its packages and versions at its top; each
// output's licences are beside it (<name>.LICENSES.txt). test/vendor.test.mjs checks the
// committed files are exactly what this writes.
//
//   npm run vendor     write them
//   vendored()         [{ path, data }]: what it writes (for the test)
import { build } from "esbuild";
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const VENDOR = new URL("site/vendor/", ROOT);
const mod = (p) => new URL(`node_modules/${p}`, ROOT).pathname;

export const BUNDLES = {
  "smartypants.js": { title: "The book site's typography (remark-smartypants 3.0.2's libraries), for the review", entry: 'export { retext } from "retext";\nexport { default as smartypants } from "retext-smartypants";\n' },
  "markdownlint.js": { title: "markdownlint 0.38.0 (lib/markdownlint.mjs), for the formatting check", entry: `export * from ${JSON.stringify(mod("markdownlint/lib/markdownlint.mjs"))};\n` },
  "js-yaml.js": { title: "js-yaml 4.1.0, for the formatting check and Credits", entry: 'export * from "js-yaml";\nexport { default } from "js-yaml";\n' },
};
// Pyodide as npm ships it: the loader, the runtime, the standard library and the lock.
export const PYODIDE = { dir: "pyodide/", pkg: "pyodide", files: ["pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"] };

