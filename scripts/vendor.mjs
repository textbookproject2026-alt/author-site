const pkgJson = (name) => JSON.parse(readFileSync(new URL(`node_modules/${name}/package.json`, ROOT), "utf8"));
const label = (name) => {
  const pj = pkgJson(name);
  return `${pj.name}@${pj.version} (${pj.license})`;
};

/** Each package's licence text (retext, retext-latin and retext-stringify ship none: MIT, per their package.json and readme). */
function licenses(names) {
  return [...names].sort().map((name) => {
    const dir = new URL(`node_modules/${name}/`, ROOT);
    const file = readdirSync(dir).find((f) => /^licen[cs]e(\.md|\.txt)?$/i.test(f));
    if (file) return `${label(name)}\n\n${readFileSync(new URL(file, dir), "utf8").trim()}\n`;
    const pj = pkgJson(name);
    if (pj.license !== "MIT") throw new Error(`${name}: no licence file and not MIT`);
    const who = String(pj.author?.name ?? pj.author ?? "").replace(/\s*<.*$/, "");
    return `${label(name)} (no licence file in the package; MIT per its package.json and readme)\n\n${MIT(who)}\n`;
  }).join(`\n${"-".repeat(72)}\n\n`);
}

async function bundle(name, { title, entry }) {
  const r = await build({
    stdin: { contents: entry, resolveDir: ROOT.pathname, sourcefile: `${name}-entry.mjs` },
    bundle: true, format: "esm", platform: "browser", target: "es2022", write: false, metafile: true, legalComments: "inline", charset: "utf8",
  });
  const pkgs = new Set();
  for (const file of Object.keys(r.metafile.inputs)) {
    const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(file);
    if (m) pkgs.add(m[1]);
  }
  const head = [`// Generated by scripts/vendor.mjs (npm run vendor); don't edit by hand.`, `// ${title}:`, ...[...pkgs].map(label).sort().map((p) => `//   ${p}`), ""].join("\n");
  return [
    { path: name, data: Buffer.from(head + r.outputFiles[0].text) },
    { path: name.replace(/\.js$/, ".LICENSES.txt"), data: Buffer.from(licenses(pkgs)) },
  ];
}

export async function vendored() {
  const out = [];
  for (const [name, b] of Object.entries(BUNDLES)) out.push(...(await bundle(name, b)));
  for (const f of PYODIDE.files) out.push({ path: PYODIDE.dir + f, data: readFileSync(new URL(`node_modules/${PYODIDE.pkg}/${f}`, ROOT)) });
  const pj = pkgJson(PYODIDE.pkg);
  out.push({ path: `${PYODIDE.dir}LICENSES.txt`, data: Buffer.from(`${label(PYODIDE.pkg)}: ${PYODIDE.files.join(", ")}, as npm ships them.\nMozilla Public License 2.0, https://mozilla.org/MPL/2.0/ (the package has no licence file of its own; source: ${pj.repository?.url ?? "https://github.com/pyodide/pyodide"}). Python's standard library (python_stdlib.zip) is under the PSF License, https://docs.python.org/3/license.html.\n`) });
  return out;
}

export const target = (path) => new URL(path, VENDOR);

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(new URL(PYODIDE.dir, VENDOR), { recursive: true });
  for (const f of await vendored()) writeFileSync(target(f.path), f.data);
  console.log(`wrote site/vendor/: ${(await vendored()).map((f) => f.path).join(", ")}`);
}
